def knowledge_refresh_for_date(report_date: date) -> AIKnowledgeRefresh:
    """Return the reproducible knowledge card assigned to ``report_date``.

    The epoch date receives the first card.  Dates before the epoch are also
    supported through Python's modulo semantics, which keeps historical report
    regeneration deterministic rather than making the catalog time-dependent.
    """

    if not isinstance(report_date, date) or isinstance(report_date, datetime):
        raise TypeError("report_date must be a date")
    offset = (report_date - KNOWLEDGE_REFRESH_EPOCH).days
    return _KNOWLEDGE_REFRESH_CARDS[offset % KNOWLEDGE_REFRESH_CARD_COUNT]


